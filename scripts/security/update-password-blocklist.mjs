import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '../..');
const SOURCE = resolve(ROOT, 'security/password-blocklist/ncsc-100k.txt');
const OUTPUT = resolve(
  ROOT,
  'src/modules/auth/password-policy/compromised-passwords.generated.ts',
);
// SecLists 100k-most-used-passwords-NCSC.txt, pinned upstream Git blob.
// Changing this fingerprint requires a documented source review.
const PINNED_SOURCE_BLOB = '38eb37702244f55fda75cab281eb2145cd7685b6';
const MIN_LENGTH = 15;

// Exact, whole-password context-specific entries; no substring matching.
const CONTEXT_ENTRIES = [
  'password123456789',
  'password1234567890',
  'passwordpassword',
  '123456789012345',
  '12345678901234567890',
  'qwertyuiopasdfgh',
  'qwertyuiopasdfghjkl',
  'correcthorsebatterystaple',
  'letmeinletmeinletmein',
  'welcome123456789',
  'changeme123456789',
  'mypassword123456',
  'iloveyouiloveyou',
  'administrator123456',
  'securepassword123',
  'ohealthpassword123',
  'ohealth123456789',
  'ohealthohealth123',
  'password12345678',
  'thisisapassword',
  'thisismypassword',
  'trustnoone123456',
  'sunshine123456789',
  'makatechlimited2026',
];
// Explicit, tightly bounded variants of likely complete passwords.
const SUFFIXES = ['1', '2', '3', '!', '123', '1234', '2026', '2027'];

function gitBlobHash(bytes) {
  return createHash('sha1')
    .update('blob ' + bytes.length + '\0')
    .update(bytes)
    .digest('hex');
}
function quote(text) {
  return "'" + text
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('\t', '\\t')
    .replaceAll('\r', '\\r')
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029') + "'";
}
function eligible(value) {
  return [...value].length >= MIN_LENGTH &&
    Buffer.byteLength(value, 'utf8') <= 1024;
}
function generate(source) {
  const candidates = new Set();
  const add = (value) => {
    const normalized = value.normalize('NFC').toLowerCase();
    if (eligible(normalized)) candidates.add(normalized);
  };
  const basePasswords = [
    ...source.split(/\r?\n/).filter(Boolean),
    ...CONTEXT_ENTRIES,
  ];
  for (const base of basePasswords) {
    const normalized = base.normalize('NFC').toLowerCase();
    add(normalized);
    if ([...normalized].length >= 12) {
      for (const suffix of SUFFIXES) add(normalized + suffix);
    }
  }
  const entries = [...candidates].sort();
  return [
    '// Generated by scripts/security/update-password-blocklist.mjs.',
    '// Source: UK NCSC 100k most-used passwords, distributed by MIT-licensed SecLists.',
    '// Source Git blob SHA-1: ' + PINNED_SOURCE_BLOB,
    '// Do not edit entries directly; run npm run password-blocklist:generate.',
    'export const COMPROMISED_PASSWORDS = [',
    ...entries.map((value) => '  ' + quote(value) + ','),
    '] as const;',
    '',
  ].join('\n');
}
const mode = process.argv[2];
if (mode !== '--write' && mode !== '--check') {
  throw new Error('Usage: node scripts/security/update-password-blocklist.mjs --write|--check');
}
const input = readFileSync(SOURCE);
const hash = gitBlobHash(input);
if (hash !== PINNED_SOURCE_BLOB) {
  throw new Error('Compromised-password source does not match pinned blob: ' + hash);
}
const generated = generate(input.toString('utf8'));
if (mode === '--write') {
  writeFileSync(OUTPUT, generated, 'utf8');
  process.stdout.write('Generated blocklist from verified NCSC snapshot.\n');
} else if (readFileSync(OUTPUT, 'utf8') !== generated) {
  throw new Error('Compromised-password blocklist drift detected. Regenerate it.');
} else {
  process.stdout.write('Compromised-password blocklist is current.\n');
}
